#!/usr/bin/env bash
# Run the site with the PUBLIC models only (no access to the release model folder needed).
#
# The release crop-view model (v26, 9 classes) and the lemon specialist are not public.
# The public v29 set at crop-scout.com/models/v29-demo/ has the same disease and
# cucumber-leaf files (identical SHA-256) plus a 5-class crop-view. This script links
# those three into vision/private/ and writes a gitignored model-metadata.local.json
# that model.php serves instead of the release metadata: v29 crop-view classes and
# hash; lemon-leaf and tomato-leaf specialists and the leaf finder dropped (not public).
# Apple and lemon therefore show as "Other" locally, and tomato leaves use the general model.
#
# Usage:
#   .venv/bin/python live/fetch_models.py --all     # downloads the 4 public files (hash-checked)
#   scripts/link-public-models.sh
#   scripts/serve.sh                                 # http://localhost:8080/vision/
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/live/models"
DEST="$ROOT/vision/private"
for name in cropscout-crop-view cropscout-disease cropscout-cucumber-leaf; do
  test -f "$SRC/$name.onnx" || { echo "missing $SRC/$name.onnx — run: .venv/bin/python live/fetch_models.py --all" >&2; exit 1; }
  ln -sf "../../live/models/$name.onnx" "$DEST/$name.onnx"
  echo "linked $name.onnx"
done
python3 - "$ROOT" <<'PY'
import json, sys, copy
root = sys.argv[1]
release = json.load(open(f"{root}/vision/private/model-metadata.json"))
public = json.load(open(f"{root}/live/model-metadata.json"))
m = copy.deepcopy(release)
m["crop_view"] = copy.deepcopy(public["crop_view"])
# Only specialists whose model is public; the tomato-leaf field classifier and the lemon model are not.
m["condition_specialists"] = [s for s in release["condition_specialists"] if s["id"] == "cucumber-leaf"]
# The leaf finder (?detector=1) is not public either: drop it so the page does not try to fetch it.
m.pop("leaf_detector", None)
m["_local_override"] = ("Local dev override, not for release: public v29 crop-view (5 classes) instead of the "
                        "v26 release model; lemon-leaf and tomato-leaf specialists and the leaf finder dropped. "
                        "Generated by scripts/link-public-models.sh.")
json.dump(m, open(f"{root}/vision/private/model-metadata.local.json", "w"), indent=2)
print("wrote vision/private/model-metadata.local.json:", m["crop_view"]["classes"])
PY
